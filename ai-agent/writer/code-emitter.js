// Turns a resolved plan into a normal, readable Playwright spec (no AI needed to run it later).
const q = s => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const SITE_CLEANUP = { // ad banners / sticky footers that cover buttons on some practice sites
  'demoqa.com': ['#fixedban', 'footer', 'iframe[id^="google_ads"]', '[id^="adplus"]']
};
function cleanupSelectors(url) {
  try { const h = new URL(url).hostname; const k = Object.keys(SITE_CLEANUP).find(d => h === d || h.endsWith('.' + d)); return k ? SITE_CLEANUP[k] : []; } catch { return []; }
}
const cleanupLine = sels => `await page.evaluate(() => { for (const s of ${JSON.stringify(sels).replace(/"/g, "'")}) document.querySelectorAll(s).forEach(e => e.remove()); });`;

function stepCode(s) {
  const loc = s.locator ? `page.${s.locator.code}` : '';
  switch (s.action) {
    case 'fill': return [`await ${loc}.fill(${q(s.value)});`];
    case 'press': return [`await ${loc}.press(${q(s.value || 'Enter')});`];
    case 'click': return [`await ${loc}.click();`];
    case 'choose': return [s.locator.force ? `await ${loc}.check({ force: true });` : `await ${loc}.click();`];
    case 'select': return [s.value == null ? `await ${loc}.selectOption({ index: 1 });` : `await ${loc}.selectOption(${q(s.value)});`];
    case 'upload': return [`await ${loc}.setInputFiles(${q(s.value || 'test-data/sample.png')});`];
    case 'dropdown': return [`await ${loc}.click({ force: true });`, `await page.getByText(${q(s.option)}, { exact: true }).last().click();`];
    case 'expectInvalid': return [`await expect(page.locator(${q(s.selector)})).not.toHaveCount(0);`];
    case 'expectGone': return [`await expect(page.getByText(${q(s.text)}).first()).toBeHidden();`];
    case 'expectUrl': return [`await expect(page).toHaveURL(${q(s.url)});`];
    case 'expectText': return [`await expect(page.getByText(${q(s.text)}).first()).toBeVisible();`];
    default: return [`// unsupported step: ${s.action}`];
  }
}

function emitSpec({ title, instruction, url, steps }) {
  const body = [];
  body.push(`await page.goto(${q(url)});`);
  const sels = cleanupSelectors(url);
  if (sels.length) body.push(cleanupLine(sels));
  for (const s of steps) body.push(...stepCode(s));
  return `// AI-GENERATED by ai-agent/writer on ${new Date().toISOString().slice(0, 10)} - safe to edit.
// Instruction: ${String(instruction).replace(/\s+/g, ' ').slice(0, 300)}
// Runs without any AI; if a locator changes later, ai-agent/healer repairs it automatically.
const { test, expect } = require('../../fixtures/ai.fixture');

test(${q(`${title} [generated]`)}, async ({ page }) => {
${body.map(l => '  ' + l).join('\n')}
});
`;
}

module.exports = { emitSpec, stepCode, cleanupSelectors, cleanupLine, q };
